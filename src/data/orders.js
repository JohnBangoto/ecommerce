// Stats calculées pour le dashboard
export const getOrderStats = () => {
  const total = mockOrders.reduce((s, o) => s + o.total, 0);
  const byStatus = mockOrders.reduce((acc, o) => {
    acc[o.status] = (acc[o.status] || 0) + 1;
    return acc;
  }, {});
  const avgBasket = total / mockOrders.length;
  return { total, byStatus, avgBasket, count: mockOrders.length };
};
